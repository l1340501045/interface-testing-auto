/** 目录相关的界面文案；编辑器与样式共用同一份，避免两处各写一句。 */

/** 未分组不是目录，而是“不属于任何目录”这个明确状态。 */
export const UNFILED_LABEL = "未分组";

/**
 * 当前值指向的目录不在可选清单里时，选择器里那条占位选项的文案。
 *
 * 不能把这个状态显示成「未分组」：那等于在界面上宣布一个用户没做过的改动，
 * 用户一保存就真的被移出原目录。目录被归档、被删、或属于别的项目都会走到这里。
 */
export function unknownFolderLabel(folderId: string): string {
  return `已失效或已归档的目录（${folderId.slice(0, 8)}…）`;
}
